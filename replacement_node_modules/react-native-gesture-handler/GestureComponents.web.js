import React from 'react'
import {
    FlatList as RNFlatList,
    Switch as RNSwitch,
    TextInput as RNTextInput,
    ScrollView as RNScrollView,
} from 'react-native'

import createNativeWrapper from './createNativeWrapper'

export const ScrollView = createNativeWrapper(RNScrollView, {
    disallowInterruption: true,
})

export const Switch = createNativeWrapper(RNSwitch, {
    shouldCancelWhenOutside: false,
    shouldActivateOnStart: true,
    disallowInterruption: true,
})
export const TextInput = createNativeWrapper(RNTextInput)
// Alldone patch: react-native-web 0.21 removed DrawerLayoutAndroid, so the
// old static named import is both undefined and a webpack warning on web. The
// app never renders this Android-only component, so keep the compatibility
// export without asking the web bundle for an export that cannot exist.
export const DrawerLayoutAndroid = undefined

export const FlatList = React.forwardRef((props, ref) => (
    <RNFlatList ref={ref} {...props} renderScrollComponent={scrollProps => <ScrollView {...scrollProps} />} />
))
