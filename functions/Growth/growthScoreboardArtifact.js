'use strict'

// The view of the growth scoreboard: a private artifact "Growth Scoreboard" in the Alldone Growth
// project, rewritten after every daily run as a new version (so the artifact's version history is
// the scoreboard's history). The numbers live in growthMetrics; this page only shows them. An edit
// made to the artifact by anyone, an agent included, is replaced by the next run.
//
// A static page: no script runs (the data block at the end is inert JSON for agents that read the
// file), every value is escaped, nothing is loaded from elsewhere.

const { SCOREBOARD_ARTIFACT_TARGETS } = require('./growthConfig')
const { STRIPE_VAT_SHARE_OF_GROSS } = require('./growthRevenue')
const {
    APPLE_DEFAULT_COMMISSION_SHARE,
    APPLE_DEFAULT_TAX_SHARE,
    ASSISTANT_TOKEN_MIX,
    E2B_SANDBOX_USD_PER_MINUTE,
    FX_TO_EUR,
    MARGIN_WINDOW_DAYS,
    VM_RUNNER_USD_PER_MINUTE,
} = require('./growthConfig')

const ARTIFACT_TITLE = 'Growth Scoreboard'
const ARTIFACT_DESCRIPTION =
    'Daily growth funnel for alldone.app: outreach pipeline, traffic (Google Analytics), signups by source, activation, paying users, revenue from actual payments, Gold spent with estimated upstream cost, and the weekly margin per paying user. Generated by the server every morning; edits are overwritten.'

const escapeHtml = value =>
    String(value === undefined || value === null ? '' : value)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;')

const formatNumber = value => (Number.isFinite(Number(value)) ? Math.round(Number(value)).toLocaleString('en-US') : '–')
const formatEur = value =>
    Number.isFinite(Number(value))
        ? `€${Number(value).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`
        : '–'
const formatShare = (part, whole) => (Number(whole) > 0 ? `${Math.round((Number(part) / Number(whole)) * 100)}%` : '–')
const formatSigned = value => (Number(value) > 0 ? `+${value}` : `${value}`)

function table(headers, rows, emptyText = 'Nothing yet.') {
    if (!rows.length) return `<p class="empty">${escapeHtml(emptyText)}</p>`
    return `<table><thead><tr>${headers.map(header => `<th>${escapeHtml(header)}</th>`).join('')}</tr></thead><tbody>${rows
        .map(row => `<tr>${row.map(cell => `<td>${escapeHtml(cell)}</td>`).join('')}</tr>`)
        .join('')}</tbody></table>`
}

const card = (label, value, note = '') =>
    `<div class="card"><div class="label">${escapeHtml(label)}</div><div class="value">${escapeHtml(
        value
    )}</div>${note ? `<div class="note">${escapeHtml(note)}</div>` : ''}</div>`

const sortedEntries = object => Object.entries(object || {}).sort((a, b) => Number(b[1]) - Number(a[1]))

function bars(history, valueOf, label) {
    const values = history.map(day => Number(valueOf(day)) || 0)
    const max = Math.max(1, ...values.map(Math.abs))
    const width = 600
    const height = 80
    const step = values.length ? width / values.length : width
    const rects = values
        .map((value, index) => {
            const barHeight = Math.max(1, (Math.abs(value) / max) * (height - 4))
            const x = index * step + 1
            const y = value >= 0 ? height - barHeight : height - 1
            return `<rect x="${x.toFixed(1)}" y="${y.toFixed(1)}" width="${Math.max(1, step - 2).toFixed(
                1
            )}" height="${barHeight.toFixed(1)}" class="${value >= 0 ? 'pos' : 'neg'}"><title>${escapeHtml(
                `${history[index].day}: ${value}`
            )}</title></rect>`
        })
        .join('')
    return `<figure><figcaption>${escapeHtml(label)}</figcaption><svg viewBox="0 0 ${width} ${height}" role="img" aria-label="${escapeHtml(
        label
    )}">${rects}</svg></figure>`
}

function renderFunnel(latest = {}, latestMargin = null) {
    const outreach = latest.outreach
    const traffic = latest.traffic || {}
    const signups = latest.signups || {}
    const short = (latest.activation || {}).shortCohort || {}
    const premium = latest.premium || {}
    const outreachText = outreach
        ? outreach.byStatus.map(status => `${status.name}: ${formatNumber(status.count)}`).join(' · ') || 'no statuses'
        : 'not available here'
    const trafficText = traffic.connected
        ? `${formatNumber(traffic.sessions)} sessions · ${formatNumber(traffic.users)} users${
              traffic.visibleShare !== null && traffic.visibleShare !== undefined
                  ? ` · GA saw ${Math.round(traffic.visibleShare * 100)}% of the real signups`
                  : ''
          }`
        : 'not connected'
    const steps = [
        ['1. Outreach (Growth project contacts)', outreachText],
        ['2. Traffic (Google Analytics, consenting visitors only)', trafficText],
        [
            '3. Signups',
            `${formatNumber(signups.count)} (${formatNumber(signups.withAttribution)} with a recorded source)`,
        ],
        [
            '4. Activation after 7 days',
            `${formatNumber(short.taskAndAssistantReply)} task + reply · ${formatNumber(
                short.connectedIntegration
            )} connected · of ${formatNumber(short.signups)}`,
        ],
        [
            '5. Paying users',
            `${formatNumber(premium.payingUsers)} · net revenue today ${formatEur(latest.revenue && latest.revenue.netEur)}`,
        ],
        [
            '6. Margin per paying user',
            latestMargin
                ? `${formatNumber(latestMargin.profitableUsers)} of ${formatNumber(latestMargin.payingUsers)} profitable · median ${formatEur(
                      (latestMargin.percentilesEur || {}).p50
                  )}`
                : 'computed on Mondays',
        ],
    ]
    return `<h2>Funnel</h2>${table(['Step', 'Today'], steps)}`
}

function renderTraffic(traffic = {}) {
    if (!traffic.connected) {
        return `<h2>Traffic</h2><p class="empty">${escapeHtml(traffic.reason || 'Google Analytics is not connected.')}</p>`
    }
    return `<h2>Traffic (Google Analytics)</h2>
<p>Only visitors who consented to analytics are counted. GA reports days in the property's time zone.</p>
${(traffic.properties || [])
    .map(property => {
        if (property.error)
            return `<h3>${escapeHtml(property.name)}</h3><p class="note">${escapeHtml(property.error)}</p>`
        const rows = sortedEntries(property.bySourceMedium)
            .slice(0, 15)
            .map(([key, sessions]) => [key, formatNumber(sessions)])
        const campaigns = sortedEntries(property.byCampaign).map(([key, sessions]) => [key, formatNumber(sessions)])
        const hosts = sortedEntries(property.byHost).map(([key, sessions]) => `${key}: ${formatNumber(sessions)}`)
        return `<h3>${escapeHtml(property.name)}: ${formatNumber(property.sessions)} sessions, ${formatNumber(
            property.users
        )} users (${formatNumber(property.newUsers)} new), ${formatNumber(property.signupEvents)} sign_up events</h3>
<p class="note">${escapeHtml(hosts.join(' · '))}</p>
${table(['Source / medium', 'Sessions'], rows)}
${campaigns.length ? table(['Campaign', 'Sessions'], campaigns) : ''}`
    })
    .join('')}`
}

function renderActivation(activation = {}) {
    const short = activation.shortCohort || {}
    const long = activation.longCohort || {}
    const shortRows = Object.entries(short.bySource || {}).map(([source, bucket]) => [
        source,
        formatNumber(bucket.signups),
        `${formatNumber(bucket.taskAndAssistantReply)} (${formatShare(bucket.taskAndAssistantReply, bucket.signups)})`,
        `${formatNumber(bucket.connectedIntegration)} (${formatShare(bucket.connectedIntegration, bucket.signups)})`,
    ])
    const longRows = Object.entries(long.bySource || {}).map(([source, bucket]) => [
        source,
        formatNumber(bucket.signups),
        `${formatNumber(bucket.goldOnThreeDays)} (${formatShare(bucket.goldOnThreeDays, bucket.signups)})`,
    ])
    return `
<h2>Activation</h2>
<p>All three candidates are measured until one is chosen. Each cohort is the signups of one day whose window has just closed.</p>
<h3>Signups of ${escapeHtml(short.day || '–')} after 7 days: ${formatNumber(short.signups)}</h3>
<p>(a) created a task and got an assistant reply: <b>${formatNumber(short.taskAndAssistantReply)}</b> (${formatShare(
        short.taskAndAssistantReply,
        short.signups
    )}) · (b) connected WhatsApp, Gmail or a calendar: <b>${formatNumber(short.connectedIntegration)}</b> (${formatShare(
        short.connectedIntegration,
        short.signups
    )})</p>
${table(['Source', 'Signups', '(a) task + reply', '(b) connected'], shortRows, 'No signups that day.')}
<h3>Signups of ${escapeHtml(long.day || '–')} after 14 days: ${formatNumber(long.signups)}</h3>
<p>(c) spent Gold on assistant work on 3 different days: <b>${formatNumber(long.goldOnThreeDays)}</b> (${formatShare(
        long.goldOnThreeDays,
        long.signups
    )})</p>
${table(['Source', 'Signups', '(c) Gold on 3 days'], longRows, 'No signups that day.')}`
}

function renderRevenue(revenue = {}) {
    const rows = [
        ...Object.entries(revenue.byProvider || {}).map(([key, bucket]) => [`provider: ${key}`, bucket]),
        ...Object.entries(revenue.byKind || {}).map(([key, bucket]) => [`kind: ${key}`, bucket]),
    ].map(([label, bucket]) => [
        label,
        formatNumber(bucket.count),
        formatEur(bucket.grossEur),
        formatEur(bucket.feeEur),
        formatEur(bucket.taxEur),
        formatEur(bucket.netEur),
    ])
    const notes = []
    if (revenue.stripeAvailable === false) notes.push('Stripe was not reachable; only Apple payments are counted.')
    if (revenue.unresolvedUserCount)
        notes.push(`${revenue.unresolvedUserCount} payment(s) could not be matched to an account.`)
    return `
<h2>Revenue of the day (actual payments)</h2>
${table(['', 'Payments', 'Gross', 'Fees', 'Tax', 'Net'], rows, 'No payments that day.')}
${notes.map(note => `<p class="note">${escapeHtml(note)}</p>`).join('')}`
}

function renderGold(gold = {}) {
    const costs = gold.estimatedCostEurBySource || {}
    const rows = sortedEntries(gold.spendBySource)
        .slice(0, 15)
        .map(([source, amount]) => [source, formatNumber(amount), formatEur(costs[source])])
    return `
<h2>Gold spent</h2>
<p>Spent <b>${formatNumber(gold.spent)}</b> · earned ${formatNumber(gold.earned)} · refunded ${formatNumber(
        gold.refunded
    )} · estimated upstream cost <b>${formatEur(gold.estimatedCostEur)}</b>${
        gold.available === false ? ' · <i>no Gold rollup for this day</i>' : ''
    }</p>
${table(['Source', 'Gold', 'Est. cost'], rows, 'No Gold spent that day.')}`
}

function renderMargin(margin, marginDay) {
    if (!margin) {
        return `<h2>Margin per paying user</h2><p class="empty">Computed every Monday; not computed yet.</p>`
    }
    const percentiles = margin.percentilesEur || {}
    const group = groups =>
        Object.entries(groups || {}).map(([key, bucket]) => [
            key,
            formatNumber(bucket.payingUsers),
            formatNumber(bucket.profitableUsers),
            formatEur(bucket.revenueEur),
            formatEur(bucket.costEur),
            formatEur(bucket.marginEur),
            formatEur(bucket.medianMarginEur),
        ])
    const headers = ['', 'Paying', 'Profitable', 'Revenue', 'Est. cost', 'Margin', 'Median']
    return `
<h2>Margin per paying user (last ${formatNumber(margin.windowDays)} days, as of ${escapeHtml(marginDay || '–')})</h2>
<p>Revenue after fees and taxes minus the estimated upstream cost of the Gold each paying user spent. <b>${formatNumber(
        margin.profitableUsers
    )} of ${formatNumber(margin.payingUsers)}</b> paying users are profitable; total margin <b>${formatEur(
        margin.marginEur
    )}</b>.</p>
${table(
    ['p10', 'p25', 'median', 'p75', 'p90'],
    [[percentiles.p10, percentiles.p25, percentiles.p50, percentiles.p75, percentiles.p90].map(formatEur)]
)}
<h3>By plan</h3>${table(headers, group(margin.byPlan))}
<h3>By account age</h3>${table(headers, group(margin.byTenure))}
<h3>By signup source</h3>${table(headers, group(margin.bySignupSource))}
${margin.unresolvedRevenueEur ? `<p class="note">${formatEur(margin.unresolvedRevenueEur)} of revenue could not be matched to an account.</p>` : ''}`
}

function renderAssumptions(rates = {}) {
    const usd = value => (Number.isFinite(Number(value)) ? `$${Number(value).toFixed(6)}` : '–')
    const assistant = Object.entries(rates.assistantUsdPerGold || {})
        .map(([model, value]) => `${model} ${usd(value)}`)
        .join(', ')
    const items = [
        `Exchange rate: 1 USD = ${FX_TO_EUR.USD} EUR.`,
        `Stripe: fees are Stripe's actual fees; VAT is estimated at ${Math.round(
            STRIPE_VAT_SHARE_OF_GROSS * 100
        )}% of the gross amount.`,
        `Apple: tax and commission come from RevenueCat; when an event lacks them, ${Math.round(
            APPLE_DEFAULT_TAX_SHARE * 100
        )}% tax and ${Math.round(APPLE_DEFAULT_COMMISSION_SHARE * 100)}% commission are assumed. Apple subscriptions count from the deploy of this scoreboard.`,
        `VM runs: $${E2B_SANDBOX_USD_PER_MINUTE} (E2B sandbox) + $${VM_RUNNER_USD_PER_MINUTE} (Cloud Run) per minute, i.e. ${usd(
            rates.vmInfraUsdPerGold
        )} per Gold; a run Alldone paid tokens for is priced at the higher of that and its token rate.`,
        `In-app assistant per Gold, with an assumed token mix of ${Math.round(ASSISTANT_TOKEN_MIX.input * 100)}% input, ${Math.round(
            ASSISTANT_TOKEN_MIX.cachedInput * 100
        )}% cached input, ${Math.round(ASSISTANT_TOKEN_MIX.output * 100)}% output: ${assistant}.`,
        `Any other Gold: ${usd(rates.defaultUsdPerGold)} per Gold (the Sol assistant rate). Game items and goal unlocks cost nothing.`,
        `Margin: subscription payments are spread over the month or year they pay for; ${MARGIN_WINDOW_DAYS}-day window; team accounts excluded.`,
        'Activation (b) reads the connections a user has on day 7.',
        'Traffic: Google Analytics only counts consenting visitors; the share of real signups it saw shows how much of the traffic is visible.',
    ]
    return `<h2>What is estimated</h2><ul>${items.map(item => `<li>${escapeHtml(item)}</li>`).join('')}</ul>`
}

function renderHistory(history) {
    const rows = [...history]
        .reverse()
        .map(day => [
            day.day,
            formatNumber(day.signups && day.signups.count),
            formatNumber(day.premium && day.premium.payingUsers),
            formatEur(day.revenue && day.revenue.netEur),
            formatNumber(day.gold && day.gold.spent),
            formatEur(day.gold && day.gold.estimatedCostEur),
        ])
    return `
<h2>Last ${history.length} days</h2>
${bars(history, day => day.signups && day.signups.count, 'Signups per day')}
${bars(history, day => day.revenue && day.revenue.netEur, 'Net revenue per day (EUR)')}
${table(['Day', 'Signups', 'Paying users', 'Net revenue', 'Gold spent', 'Est. Gold cost'], rows)}`
}

