function renderScoreboardHtml({
    latest = {},
    history = [],
    latestMargin = null,
    latestMarginDay = null,
    rates = {},
    generatedAt,
}) {
    const premium = latest.premium || {}
    const signups = latest.signups || {}
    const active = latest.activeUsers || {}
    const sourceRows = sortedEntries(signups.bySource).map(([source, count]) => [source, formatNumber(count)])
    const campaignRows = sortedEntries(signups.byCampaign).map(([campaign, count]) => [campaign, formatNumber(count)])
    const payingNote =
        premium.started === null || premium.started === undefined
            ? 'first snapshot'
            : `${formatSigned(premium.started)} started · ${premium.stopped ? `−${premium.stopped}` : '0'} stopped`
    const data = { latest, latestMargin, latestMarginDay, history }

    return `<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(ARTIFACT_TITLE)}</title><style>${STYLE}</style></head>
<body>
<h1>${escapeHtml(ARTIFACT_TITLE)}</h1>
<p class="meta">Day ${escapeHtml(latest.day || '–')} (UTC) · generated ${escapeHtml(
        generatedAt ? new Date(generatedAt).toISOString().replace('T', ' ').slice(0, 16) : '–'
    )} UTC from server data. Edits to this page are replaced by the next run.</p>
<div class="cards">
${card('Signups', formatNumber(signups.count), `${formatNumber(signups.withAttribution)} with a recorded source`)}
${card('Paying users', formatNumber(premium.payingUsers), payingNote)}
${card('Net revenue', formatEur(latest.revenue && latest.revenue.netEur), 'after fees and taxes')}
${card('Gold spent', formatNumber(latest.gold && latest.gold.spent), `≈ ${formatEur(latest.gold && latest.gold.estimatedCostEur)} upstream`)}
${card('Active users', formatNumber(active.week), `${formatNumber(active.day)} today · ${formatNumber(active.month)} in 30 days`)}
</div>
${renderFunnel(latest, latestMargin)}
${renderTraffic(latest.traffic)}
<h2>Signups by source</h2>
${table(['Source', 'Signups'], sourceRows, 'No signups that day.')}
${campaignRows.length ? `<h3>By campaign</h3>${table(['Campaign', 'Signups'], campaignRows)}` : ''}
${renderActivation(latest.activation)}
${renderRevenue(latest.revenue)}
${renderGold(latest.gold)}
${renderMargin(latestMargin, latestMarginDay)}
${renderHistory(history)}
${renderAssumptions(rates)}
<script type="application/json" id="growth-scoreboard-data">${JSON.stringify(data)
        .replace(/</g, '\\u003c')
        .replace(/>/g, '\\u003e')
        .replace(/&/g, '\\u0026')}</script>
</body></html>
`
}

// Writes the page as a new version of the scoreboard artifact, creating it on the first run (or
// again if somebody deleted it). Returns the artifact id to remember, or null when this
// environment has no scoreboard artifact.
async function publishScoreboardArtifact({ html, day, artifactId, environment, commit }) {
    const target = SCOREBOARD_ARTIFACT_TARGETS[environment]
    if (!target) return null
    const commitVersion = commit || require('../Artifacts/artifactStore').commitArtifactVersion
    const input = {
        userId: target.ownerUserId,
        projectId: target.projectId,
        files: [{ path: 'index.html', base64: Buffer.from(html, 'utf8').toString('base64') }],
        title: ARTIFACT_TITLE,
        description: ARTIFACT_DESCRIPTION,
        isPrivate: true,
        changeSummary: `Scoreboard for ${day}`,
    }
    if (artifactId) {
        try {
            const result = await commitVersion({ ...input, artifactId })
            return result.artifactId
        } catch (error) {
            if (error && error.code !== 'not-found') throw error
        }
    }
    const created = await commitVersion(input)
    return created.artifactId
}

